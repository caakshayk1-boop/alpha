import { chromium, webkit } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
const base = process.env.APEX_BASE || 'http://localhost:8810';
import { screen, chart, pulse, company } from './fixtures.mjs';
await mkdir('/tmp/apexpro-checks',{recursive:true});
for (const [name, engine] of [['chromium',chromium],['webkit',webkit]].filter(([name]) => !process.env.APEX_ENGINE || process.env.APEX_ENGINE === name)) {
 const browser = await engine.launch();
 const context = await browser.newContext({viewport:{width:1440,height:1000},serviceWorkers:'block'});
 const page = await context.newPage(), errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/**',async route=>{
  const path = new URL(route.request().url()).pathname;
  const data = {'/api/screen':screen,'/api/market':pulse,'/api/company':company,'/api/chart':chart,'/api/spark':{t:chart.t.slice(-60),c:chart.c.slice(-60)}}[path];
  await route.fulfill({status:data?200:404,contentType:'application/json',body:JSON.stringify(data||{})});
 });
 await page.goto(base);
 await page.getByRole('heading',{name:'Your market workspace'}).waitFor();
 assert.equal(await page.locator('.market-card').count(),4);
 await page.screenshot({path:`/tmp/apexpro-checks/${name}-overview.png`,fullPage:true,animations:'disabled'});
 await page.locator('#sidebar a[href="#/discover"]').click();
 await page.locator('#filter-query').fill('TCS');
 assert.equal(await page.locator('tbody tr').count(),1);
 await page.locator('tbody .company-cell').click();
 await page.locator('#note-form').waitFor();
 await page.getByRole('heading',{name:'Financial history'}).waitFor();
 await page.locator('textarea[name=thesis]').fill('Durable cash generation, subject to growth recovery.');
 await page.getByRole('button',{name:'1Y',exact:true}).click();
 assert.equal(await page.locator('textarea[name=thesis]').inputValue(),'Durable cash generation, subject to growth recovery.');
 await page.locator('textarea[name=risk]').fill('Cash conversion below one for two years.');
 await page.locator('input[name=review]').fill('2026-12-15');
 await page.getByRole('button',{name:'Save research'}).click();
 assert.match(await page.locator('#toast').innerText(),/saved/);
 await page.getByRole('button',{name:'Compare',exact:true}).click();
 await page.getByRole('button',{name:'Add company +',exact:true}).click();
 await page.locator('#global-search').fill('INFY');
 await page.locator('.search-result').first().click();
 assert.equal(await page.locator('.compare-card').count(),2);
 await page.locator('#sidebar a[href="#/desk"]').click();
 assert.match(await page.locator('.journal-card').innerText(),/Durable cash generation/);
 await page.reload();
 await page.locator('.journal-card').waitFor();
 assert.match(await page.locator('.journal-card').innerText(),/Durable cash generation/);
 await page.setViewportSize({width:390,height:844});
 await page.locator('#mobile-nav a[href="#/"]').click();
 await page.getByRole('heading',{name:'Your market workspace'}).waitFor();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), 'mobile page must not overflow');
 await page.screenshot({path:`/tmp/apexpro-checks/${name}-mobile.png`,fullPage:true,animations:'disabled'});
 await page.locator('.top-actions a[href="#/settings"]').click();
 await page.getByRole('switch',{name:'Colourblind palette'}).click();
 assert.equal(await page.locator('html').getAttribute('data-colorblind'),'true');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.locator('#mobile-nav a[href="#/discover"]').click();
 await page.getByRole('heading',{name:'Company research',exact:true}).waitFor();
 assert.equal(await page.locator('.page-heading').evaluate(e=>getComputedStyle(e).animationName),'none');
 assert.deepEqual(errors,[]);
 console.log(`${name}: overview, filtering, company, range/draft, save/reload, comparison, mobile overflow, display preferences, reduced motion passed`);
 await context.close(); await browser.close();
}
