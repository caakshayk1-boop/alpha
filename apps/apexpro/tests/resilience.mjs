import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const base=process.env.APEX_BASE || 'http://localhost:8810';
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:390,height:844}}), page=await context.newPage();
await page.goto(base);
await page.locator('.canvas-layout').waitFor({timeout:30000});
await page.evaluate(()=>navigator.serviceWorker.ready);
await page.reload();
await page.locator('.canvas-layout').waitFor();
const actualCount=await page.locator('.canvas-pagination>span').innerText();
assert.ok(parseInt(actualCount.replace(/,/g,''))>100,'Real screen should cover over 100 companies');
await page.goto(base+'/#/company/TCS');
await page.locator('#note-form').waitFor();
await page.waitForFunction(()=>document.querySelector('.company-chart .price-chart'));
await page.locator('textarea[name=thesis]').fill('Real feed integration note');
await page.getByRole('button',{name:'Save research',exact:true}).click();
await page.goto(base+'/#/desk');
const downloadEvent=page.waitForEvent('download');
await page.getByRole('button',{name:'Export backup'}).click();
const download=await downloadEvent;
const exported=JSON.parse(await readFile(await download.path(),'utf8'));
assert.equal(exported.notes.TCS.thesis,'Real feed integration note');
assert.ok(exported.researchTrail.some(e=>e.kind==='note'&&e.symbol==='TCS'));
const trailBefore=await page.evaluate(()=>localStorage.getItem('apexpro:trail'));
await page.locator('#import-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({schema:'apexpro-desk/1',watch:['INFY'],notes:{INFY:{thesis:'Imported note'},TCS:{thesis:'Must not replace'}}}))});
await page.getByText('Imported note',{exact:true}).waitFor();
assert.equal(await page.evaluate(()=>localStorage.getItem('apexpro:trail')),trailBefore);
assert.match(await page.locator('.journal-grid').innerText(),/Real feed integration note/);
await context.setOffline(true);
await page.goto(base+'/#/');
await page.locator('.canvas-layout').waitFor();
assert.match(await page.locator('.notice').innerText(),/cached data/);
await page.goto(base+'/#/desk');
assert.match(await page.locator('.journal-grid').innerText(),/Real feed integration note/);
console.log('Real screen/company/chart, service worker, offline reload, saved research, backup export and safe merge passed');
await context.close();
const failure=await browser.newContext({serviceWorkers:'block'}), p=await failure.newPage();
await p.route('**/api/**',r=>r.fulfill({status:502,contentType:'application/json',body:'{"error":"unavailable"}'}));
await p.goto(base);
await p.getByRole('heading',{name:'Unable to load the company screen'}).waitFor();
await p.getByRole('link',{name:'My Desk',exact:true}).first().click();
await p.getByRole('heading',{name:'Your research desk'}).waitFor();
await p.goto(base+'/#/%E0%A4%A');
assert.ok(await p.locator('body').innerText());
console.log('Feed failure stays readable, saved desk accessible, malformed URLs do not crash');
await failure.close(); await browser.close();
