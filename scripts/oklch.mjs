// oklch.mjs — writes src/app/tokens-oklch.css: the theme colour tokens of globals.css, authored in OKLCH (Pro §24.1) and
// applied only where the browser supports it. The hex values in globals.css stay as the fallback, and the two agree to
// within rounding (a test re-converts and compares). Run after changing a hex token: node scripts/oklch.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const css = readFileSync('src/app/globals.css', 'utf8');
const block = (sel) => { const i = css.indexOf(`${sel} {`); return css.slice(i, css.indexOf('\n}', i)); };
const toLin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
export function hexToOklch(hex) {
  const h = hex.replace('#', '');
  const [r, g, b] = (h.length === 3 ? h.split('').map((x) => x + x) : h.match(/../g)).map((x) => toLin(parseInt(x, 16) / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  const C = Math.hypot(A, B);
  const H = C < 1e-4 ? 0 : ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360;
  return `oklch(${(L * 100).toFixed(2)}% ${C.toFixed(4)} ${H.toFixed(2)})`;
}
/** Every top-level rule (and every rule inside an @media/@supports block) that declares custom properties, in order. */
function tokenRules(text) {
  const out = [];
  const walk = (src, wrap) => {
    let i = 0;
    while (i < src.length) {
      const open = src.indexOf('{', i);
      if (open < 0) break;
      const head = src.slice(i, open).replace(/\/\*[\s\S]*?\*\//g, '').trim();
      let depth = 1, j = open + 1;
      while (j < src.length && depth) { if (src[j] === '{') depth++; else if (src[j] === '}') depth--; j++; }
      const body = src.slice(open + 1, j - 1);
      if (head.startsWith('@media') || head.startsWith('@supports')) walk(body, head);
      else if (!head.startsWith('@')) {
        const decls = [...body.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)];
        if (decls.length) out.push({ wrap, head, decls: decls.map(([, k, v]) => [k, v.trim()]) });
      }
      i = j;
    }
  };
  walk(text, null);
  return out;
}
const HEX = /^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/;
if (process.argv[1]?.endsWith('oklch.mjs')) {
  const rules = tokenRules(css);
  let n = 0;
  const lines = rules.map(({ wrap, head, decls }) => {
    const body = decls.map(([k, v]) => { if (HEX.test(v)) { n++; return `  ${k}: ${hexToOklch(v)}; /* ${v} */`; } return `  ${k}: ${v};`; }).join('\n');
    const rule = `${head} {\n${body}\n}`;
    return wrap ? `${wrap} {\n${rule}\n}` : rule;
  });
  writeFileSync('src/app/tokens-oklch.css', `/* Generated by scripts/oklch.mjs from globals.css. Do not edit by hand.\n   Every custom-property rule of globals.css replayed in the same order, so every theme, accent, market and contrast\n   mode resolves exactly as before; hex values are authored here in OKLCH. Browsers without OKLCH keep globals.css. */\n@supports (color: oklch(0% 0 0)) {\n${lines.join('\n')}\n}\n`);
  console.log(`tokens-oklch.css: ${rules.length} rules, ${n} colours in OKLCH`);
}
